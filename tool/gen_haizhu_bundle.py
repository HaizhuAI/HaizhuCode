#!/usr/bin/env python3
"""Generates lib/builtin/setup/haizhu_bundle.dart from the haizhu/ payload tree.

Run from the repo root:  python tool/gen_haizhu_bundle.py
Re-run whenever haizhu/ changes; the generated file is committed.
"""
import base64
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "haizhu"
OUT = ROOT / "lib" / "builtin" / "setup" / "haizhu_bundle.dart"


def main() -> int:
    if not SRC.is_dir():
        sys.exit("haizhu/ payload tree is missing")
    files = sorted(p for p in SRC.rglob("*") if p.is_file())
    entries = []
    digest = hashlib.sha256()
    total_bytes = 0
    for path in files:
        rel = path.relative_to(SRC).as_posix()
        data = path.read_bytes()
        total_bytes += len(data)
        digest.update(rel.encode() + b"\0" + data)
        entries.append((rel, base64.b64encode(data).decode()))
    bundle_sha = digest.hexdigest()
    lines = [
        "/// GENERATED by tool/gen_haizhu_bundle.py — do not edit by hand.",
        "/// Re-run the generator after changing anything under haizhu/.",
        "library;",
        "",
        "/// The HaizhuCode payload: every file under haizhu/, base64-encoded,",
        "/// keyed by its path relative to the payload root.",
        "/// [HaizhuSetupComponent] decodes each entry into `/opt/haizhu/<path>`.",
        "abstract final class HaizhuBundle {",
        f"  static const version = '{(SRC / 'VERSION').read_text().strip()}';",
        f"  static const sha256 = '{bundle_sha}';",
        "  static const root = '/opt/haizhu';",
        f"  static const totalBytes = {total_bytes};",
        "  static const files = <String, String>{",
    ]
    for rel, b64 in entries:
        escaped = rel.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"    '{escaped}':")
        # The ratchet caps every lib file at 1500 lines; 4k-char chunks keep
        # the generated map small while staying diffable in review.
        chunks = [b64[i : i + 4000] for i in range(0, len(b64), 4000)]
        if len(chunks) == 1:
            lines.append(f"      '{chunks[0]}',")
        else:
            for i, chunk in enumerate(chunks):
                sep = "," if i == len(chunks) - 1 else ""
                lines.append(f"      '{chunk}'{sep}")
    lines += ["  };", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(entries)} files, {OUT.stat().st_size} bytes -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
